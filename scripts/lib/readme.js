'use strict';
// README generator for workflows. Generated text lives between markers; text outside survives regeneration.
const path = require('node:path');
const { toMermaid, shortType, isTriggerType } = require('./diagram');
const { nameFromRef, WORKFLOW_REF_TYPES } = require('./normalize');

const BEGIN = '<!-- n8n-docs:begin (generated by scripts/n8n-docs.js; do not edit between markers) -->';
const END = '<!-- n8n-docs:end -->';

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const code = (s) => '`' + String(s).replace(/`/g, "'") + '`';

function purpose(wf) {
  if (wf.description) return wf.description.trim();
  const notes = (wf.nodes || []).filter((n) => /stickyNote$/.test(n.type) && n.parameters && n.parameters.content);
  if (notes.length) {
    return notes.map((n) => String(n.parameters.content).trim()).join('\n\n').split('\n').map((l) => `> ${l}`).join('\n');
  }
  return '_No description. Set the workflow description in n8n or add a sticky note, then re-run the generator._';
}

function triggerDetail(n) {
  const t = shortType(n.type);
  const p = n.parameters || {};
  if (t === 'webhook') return `${p.httpMethod || 'GET'} ${p.path ? '/' + p.path : '(no path set)'}`;
  if (t === 'scheduleTrigger' && p.rule) return JSON.stringify(p.rule);
  if (t === 'executeWorkflowTrigger') return 'called from another workflow';
  if (t === 'errorTrigger') return 'runs when another workflow fails';
  return '';
}

function inputsSection(wf) {
  const trig = (wf.nodes || []).find((n) => shortType(n.type) === 'executeWorkflowTrigger');
  if (!trig) return '_Not a sub-workflow entry point; see Trigger._';
  const p = trig.parameters || {};
  const src = p.inputSource || 'workflowInputs';
  if (src === 'workflowInputs') {
    const vals = (p.workflowInputs && p.workflowInputs.values) || [];
    if (!vals.length) return '_No inputs declared._';
    return ['| Field | Type |', '| --- | --- |', ...vals.map((v) => `| ${cell(v.name)} | ${cell(v.type || 'any')} |`)].join('\n');
  }
  if (src === 'jsonExample') return 'Example payload:\n\n```json\n' + String(p.jsonExample || '').trim() + '\n```';
  return '_Accepts all incoming data (inputs not declared)._';
}

function outputsSection(wf) {
  const nodes = (wf.nodes || []).filter((n) => !/stickyNote$/.test(n.type));
  const hasOut = new Set();
  for (const [src, types] of Object.entries(wf.connections || {})) {
    const slots = types.main || [];
    if (slots.some((s) => s && s.length)) hasOut.add(src);
  }
  const last = nodes.filter((n) => !hasOut.has(n.name) && !(n.type.includes('.if') && false));
  const resp = nodes.filter((n) => /respondToWebhook$/.test(n.type));
  const names = [...new Set([...resp, ...last].map((n) => n.name))];
  if (!names.length) return '_No terminal node._';
  return 'Data produced by the terminal node(s): ' + names.map(code).join(', ');
}

function errorSection(wf, link) {
  const out = [];
  const e = nameFromRef(wf.settings && wf.settings.errorWorkflow);
  out.push(e ? `Error workflow: ${link(e)}` : 'Error workflow: none declared (`settings.errorWorkflow` is empty).');
  const cont = (wf.nodes || []).filter((n) => n.onError && n.onError !== 'stopWorkflow');
  if (cont.length) out.push('Nodes with custom error handling: ' + cont.map((n) => `${code(n.name)} (${n.onError})`).join(', '));
  const retry = (wf.nodes || []).filter((n) => n.retryOnFail);
  if (retry.length) out.push('Nodes with retry: ' + retry.map((n) => `${code(n.name)} (${n.maxTries || 3}x)`).join(', '));
  return out.map((l) => `- ${l}`).join('\n');
}

/**
 * @param {object} wf normalized workflow
 * @param {{relDir: string, relDirByName: Map<string,string>, calledBy: Map<string,string[]>}} ctx
 */
function generateBlock(wf, ctx) {
  const link = (name) => {
    const d = ctx.relDirByName.get(name);
    if (!d) return code(name);
    return `[${name}](${path.posix.relative(ctx.relDir, d) || '.'}/README.md)`;
  };
  const nodes = (wf.nodes || []).filter((n) => !/stickyNote$/.test(n.type));
  const triggers = nodes.filter((n) => isTriggerType(n.type));
  const calls = [];
  for (const n of nodes) {
    if (WORKFLOW_REF_TYPES.has(n.type) && n.parameters) {
      const name = nameFromRef(n.parameters.workflowId);
      if (name) calls.push(`${code(n.name)} -> ${link(name)}`);
    }
  }
  const calledBy = (ctx.calledBy.get(wf.name) || []).map(link);
  const L = [];
  L.push(BEGIN, '', '## Diagram', '', '```mermaid', toMermaid(wf), '```', '');
  L.push('## Purpose', '', purpose(wf), '');
  L.push('## Trigger', '');
  L.push(triggers.length
    ? triggers.map((n) => `- ${code(n.name)} (${shortType(n.type)})${triggerDetail(n) ? ': ' + triggerDetail(n) : ''}`).join('\n')
    : '_No trigger node (manual/API execution only)._');
  L.push('', '## Inputs', '', inputsSection(wf), '');
  L.push('## Outputs', '', outputsSection(wf), '');
  L.push('## Error handling', '', errorSection(wf, link), '');
  if (calls.length || calledBy.length) {
    L.push('## Related workflows', '');
    if (calls.length) L.push('Calls:', '', ...calls.map((c) => `- ${c}`), '');
    if (calledBy.length) L.push('Called by:', '', ...calledBy.map((c) => `- ${c}`), '');
  }
  L.push('## Nodes', '', '| Node | Type | Credential |', '| --- | --- | --- |');
  for (const n of nodes) {
    const creds = Object.values(n.credentials || {}).map((c) => c.name).filter(Boolean).join(', ');
    L.push(`| ${cell(n.name)} | ${cell(shortType(n.type))} | ${cell(creds)} |`);
  }
  L.push('', END);
  return L.join('\n');
}

/** Merge generated block into existing README text (or create). Text outside markers is preserved. */
function mergeReadme(existing, wf, block) {
  if (existing == null) {
    return `# ${wf.name}\n\n${block}\n\n## Notes\n\n<!-- Manual notes go here; they survive regeneration. -->\n`;
  }
  const b = existing.indexOf('<!-- n8n-docs:begin');
  const e = existing.indexOf(END);
  if (b !== -1 && e !== -1 && e > b) return existing.slice(0, b) + block + existing.slice(e + END.length);
  return existing.replace(/\s*$/, '\n\n') + block + '\n';
}

module.exports = { generateBlock, mergeReadme, BEGIN, END };
