// ---------------------------------------------------------------------------
// Code-node embedding
// ---------------------------------------------------------------------------
function moduleSource(name) {
  return fs.readFileSync(path.join(SRC, `${name}.js`), 'utf8').trimEnd();
}

function dependencyOrder(names) {
  const order = [];
  const visit = (name) => {
    if (order.includes(name)) return;
    for (const m of moduleSource(name).matchAll(/require\('\.\/([a-z0-9-]+)'\)/g)) visit(m[1]);
    order.push(name);
  };
  names.forEach(visit);
  return order;
}

function embed(modules, body) {
  const names = dependencyOrder(modules);
  const lines = [
    '// ---- Embedded from code/src (generated by code/tools/build-workflows.js; edit code/src, not here) ----',
    'const __defs = {};',
  ];
  for (const name of names) {
    lines.push(`// >>> code/src/${name}.js`);
    lines.push(`__defs['./${name}'] = function (module, exports, require) {`);
    lines.push(moduleSource(name));
    lines.push('};');
    lines.push(`// <<< code/src/${name}.js`);
  }
  lines.push(
    'const __cache = {};',
    'function __require(id) {',
    '  if (!__cache[id]) { const module = { exports: {} }; __defs[id](module, module.exports, __require); __cache[id] = module.exports; }',
    '  return __cache[id];',
    '}',
    '// ---- End of embedded modules ----',
    '',
    body.trim(),
  );
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Node helpers
// ---------------------------------------------------------------------------
const { sha256Hex: nodeHash } = require(path.join(SRC, 'sha256.js'));
function nodeId(workflowKey, name) {
  // Deterministic UUID-shaped id from workflow + node name (stable diffs).
  const h = nodeHash(`${workflowKey}/${name}`);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

function node(wfKey, name, type, typeVersion, position, parameters, extra = {}) {
  return { parameters, id: nodeId(wfKey, name), name, type, typeVersion, position, ...extra };
}

function sticky(wfKey, title, content, position, width = 360, height = 260, color = 7) {
  return node(wfKey, title, 'n8n-nodes-base.stickyNote', V.sticky, position, { content, width, height, color });
}

function codeNode(wfKey, name, position, jsCode, extra = {}) {
  return node(wfKey, name, 'n8n-nodes-base.code', V.code, position, { jsCode }, extra);
}

function setNode(wfKey, name, position, fields, includeOtherFields = false) {
  const assignments = fields.map(([field, type, value]) => ({ id: nodeId(wfKey, `${name}/${field}`), name: field, value, type }));
  const parameters = { assignments: { assignments }, options: {} };
  if (includeOtherFields) parameters.includeOtherFields = true;
  return node(wfKey, name, 'n8n-nodes-base.set', V.set, position, parameters);
}

function condition(wfKey, name, leftValue, operator, rightValue) {
  const c = { id: nodeId(wfKey, `${name}/cond`), leftValue, operator };
  if (rightValue !== undefined) c.rightValue = rightValue;
  return {
    options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
    conditions: [c],
    combinator: 'and',
  };
}

function ifNode(wfKey, name, position, leftValue, operator, rightValue) {
  return node(wfKey, name, 'n8n-nodes-base.if', V.if, position, {
    conditions: condition(wfKey, name, leftValue, operator, rightValue),
    options: {},
  });
}

const IS_TRUE = { type: 'boolean', operation: 'true', singleValue: true };

function postgresQuery(wfKey, name, position, query, replacementExpr, extra = {}) {
  return node(wfKey, name, 'n8n-nodes-base.postgres', V.postgres, position, {
    operation: 'executeQuery',
    query,
    options: { queryReplacement: replacementExpr },
  }, { credentials: CRED.postgres, ...extra });
}

// Execute Workflow Trigger with declared, typed inputs ("Define using fields below").
function subTrigger(wfKey, position, inputs) {
  return node(wfKey, 'When called by another workflow', 'n8n-nodes-base.executeWorkflowTrigger', V.execWfTrigger, position, {
    inputSource: 'workflowInputs',
    workflowInputs: { values: inputs.map(([name, type]) => ({ name, type })) },
  });
}

// Execute Sub-workflow call with mapped inputs.
function callSub(wfKey, name, position, target, inputs) {
  return node(wfKey, name, 'n8n-nodes-base.executeWorkflow', V.execWf, position, {
    workflowId: { __rl: true, value: target.id, mode: 'list', cachedResultName: target.name },
    workflowInputs: {
      mappingMode: 'defineBelow',
      value: Object.fromEntries(inputs.map(([field, , expr]) => [field, expr])),
      matchingColumns: [],
      schema: inputs.map(([field, type]) => ({
        id: field, displayName: field, required: false, defaultMatch: false, display: true, canBeUsedToMatch: true, type,
      })),
      attemptToConvertTypes: false,
      convertFieldsToString: false,
    },
    mode: 'each',
    options: { waitForSubWorkflow: true },
  });
}

function connect(connections, from, to, outputIndex = 0) {
  connections[from] ??= { main: [] };
  while (connections[from].main.length <= outputIndex) connections[from].main.push([]);
  connections[from].main[outputIndex].push({ node: to, type: 'main', index: 0 });
}

function chain(connections, ...names) {
  for (let i = 0; i < names.length - 1; i++) connect(connections, names[i], names[i + 1]);
}

function workflow(key, nodes, connections, { description, isErrorHandler = false } = {}) {
  const wf = WF[key];
  const settings = {
    executionOrder: 'v1',
    saveDataErrorExecution: 'all',
    saveDataSuccessExecution: 'none',
    saveManualExecutions: false,
    // Not 'workflowsFromAList': callerIds hold instance-specific ids that normalization
    // cannot map by name, so a restricted list would break after import on another instance.
    callerPolicy: 'workflowsFromSameOwner',
  };
  if (!isErrorHandler) settings.errorWorkflow = WF.errors.id;
  return {
    id: wf.id,
    name: wf.name,
    description,
    active: false,
    nodes,
    connections,
    settings,
    pinData: {},
    meta: { templateCredsSetupCompleted: false, generatedBy: 'code/tools/build-workflows.js' },
    tags: [],
  };
}

